#!/usr/bin/env bash
# Prepare an agent worktree (AGENTS.md § Workflow). Idempotent; safe to re-run.
#   - fast-forwards a fresh branch to origin/main
#   - installs deps, builds @paypure/domain, generates the Prisma client
#   - writes .env with this worktree's own compose project name and ports
#   - points git at .githooks (pre-push gate)
# Run by: scripts/agent/new.sh, the Claude Code SessionStart hook, Cursor's
# .cursor/worktrees.json. Exits 0 without doing anything in the primary checkout.
set -euo pipefail
source "$(dirname "$0")/lib.sh"
cd "$(wt_root)"

if ! in_linked_worktree; then
  say "primary checkout: nothing to set up (agents work in worktrees)."
  exit 0
fi

# 1. Start from current main. A branch with no commits of its own can be
# fast-forwarded safely (claude -w may branch off a stale local main).
git fetch -q origin main || warn "git fetch failed; continuing offline"
if [ -z "$(git rev-list origin/main..HEAD 2>/dev/null)" ] &&
  ! git merge-base --is-ancestor origin/main HEAD 2>/dev/null; then
  if [ -z "$(git status --porcelain)" ]; then
    git merge -q --ff-only origin/main && say "fast-forwarded to origin/main"
  else
    warn "branch is behind origin/main and the tree is dirty; not fast-forwarding"
  fi
fi

# 2. Compose slot: unique per worktree, stable once written.
if [ -f .env ] && ! grep -qF "$ENV_MARKER" .env; then
  warn ".env exists and was not generated by setup.sh; leaving it alone."
  warn "Your compose stack may collide with another one; see AGENTS.md § Dev stack."
elif [ -z "$(env_get PAYPURE_SLOT)" ]; then
  used=" "
  while read -r wt; do
    [ -f "$wt/.env" ] || continue
    s=$(sed -n 's/^PAYPURE_SLOT=//p' "$wt/.env" | tail -n1)
    [ -n "$s" ] && used="$used$s "
  done < <(git worktree list --porcelain | sed -n 's/^worktree //p')
  listening=$(ss -ltnH 2>/dev/null | awk '{print $4}' | grep -oE '[0-9]+$' || true)
  slot=""
  for s in $(seq 1 99); do
    case "$used" in *" $s "*) continue ;; esac
    base=$((20000 + s * 10))
    if printf '%s\n' "$listening" | grep -qE "^$((base / 10))[0-6]$"; then
      continue
    fi
    slot=$s
    break
  done
  [ -n "$slot" ] || die "no free compose slot (1-99); prune old worktrees"
  base=$((20000 + slot * 10))
  name=$(basename "$(wt_root)" | tr '[:upper:]' '[:lower:]' | tr -c 'a-z0-9_\n-' '-')
  cat >.env <<EOF
$ENV_MARKER (worktree stack config; gitignored)
PAYPURE_SLOT=$slot
COMPOSE_PROJECT_NAME=paypure-wt-$name
CLIENT_PORT=$base
API_PORT=$((base + 1))
POSTGRES_PORT=$((base + 2))
API_DEBUG_PORT=$((base + 3))
CLIENT_DEBUG_PORT=$((base + 4))
MAILPIT_PORT=$((base + 5))
ADMINER_PORT=$((base + 6))
PUBLIC_URL=http://localhost:$base
EOF
  say "wrote .env: compose project paypure-wt-$name, ports $base-$((base + 6))"
fi

# 3. Git hooks (shared config; the hook itself skips the primary checkout).
git config core.hooksPath .githooks

# 4. Dependencies and generated code, on the host.
say "pnpm install"
pnpm install --frozen-lockfile --prefer-offline --reporter=silent
say "build @paypure/domain, prisma generate, next typegen"
pnpm --filter @paypure/domain build >/dev/null
DATABASE_URL="${DATABASE_URL:-postgresql://unused@localhost/unused}" \
  pnpm --filter api exec prisma generate >/dev/null
pnpm --filter client exec next typegen >/dev/null

touch "$(wt_gitdir)/paypure-setup-done"
say "ready. Gate: scripts/agent/check.sh   Ship: scripts/agent/land.sh"
