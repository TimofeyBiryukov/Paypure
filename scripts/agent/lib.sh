# Shared helpers for scripts/agent/*. Source it; don't run it.
# shellcheck shell=bash

say() { printf '\033[1;34m[agent]\033[0m %s\n' "$*" >&2; }
warn() { printf '\033[1;33m[agent]\033[0m %s\n' "$*" >&2; }
die() {
  printf '\033[1;31m[agent]\033[0m %s\n' "$*" >&2
  exit "${2:-1}"
}

# Top of the current checkout (worktree or primary).
wt_root() { git rev-parse --show-toplevel; }

# The primary checkout: the directory holding the shared .git.
primary_root() { dirname "$(git rev-parse --path-format=absolute --git-common-dir)"; }

# True when the current directory is inside a linked worktree.
in_linked_worktree() {
  local gd cd
  gd=$(git rev-parse --path-format=absolute --git-dir)
  cd=$(git rev-parse --path-format=absolute --git-common-dir)
  [ "$(realpath "$gd")" != "$(realpath "$cd")" ]
}

require_linked_worktree() {
  in_linked_worktree || die "This runs in an agent worktree, not the primary checkout.
Create one first: scripts/agent/new.sh <name>   (or: claude -w <name>)"
}

# Per-worktree marker/stamp files live in the worktree's private git dir.
wt_gitdir() { git rev-parse --path-format=absolute --git-dir; }

# Value of KEY from the worktree's generated .env, empty if absent.
env_get() {
  local f
  f="$(wt_root)/.env"
  [ -f "$f" ] && sed -n "s/^$1=//p" "$f" | tail -n1
}

